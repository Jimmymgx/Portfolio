import { mkdir, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { env } from "../../config/env.js";
import { Errors } from "../errors/app-error.js";

/**
 * Where uploaded files live. The database stores only the key and the public URL, never the bytes.
 * Local disk is for development; S3-compatible storage (AWS S3, Cloudflare R2, MinIO, ...) is for production.
 */
export interface StorageProvider {
  readonly name: "LOCAL" | "S3";
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  remove(key: string): Promise<void>;
  /** Value stored in `Media.publicUrl`. Local files use a path (`/media/...`) so the API address can change. */
  urlFor(key: string): string;
}

/** Storage keys are generated by the server, but guard anyway: no traversal, no odd characters. */
const SAFE_KEY = /^[a-zA-Z0-9][a-zA-Z0-9/_.-]*$/;

function assertKey(key: string) {
  if (!SAFE_KEY.test(key) || key.includes("..") || key.includes("//")) throw Errors.upload("Invalid storage key");
}

class LocalStorage implements StorageProvider {
  readonly name = "LOCAL" as const;
  readonly root = path.resolve(process.cwd(), env.LOCAL_UPLOAD_DIRECTORY);

  private resolve(key: string) {
    assertKey(key);
    const target = path.resolve(this.root, key);
    if (!target.startsWith(this.root + path.sep)) throw Errors.upload("Invalid storage key");
    return target;
  }

  async put(key: string, body: Buffer) {
    const target = this.resolve(key);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, body, { flag: "wx" });
  }

  async remove(key: string) {
    try {
      await unlink(this.resolve(key));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
    }
  }

  urlFor(key: string) {
    return `/media/${key}`;
  }
}

class S3Storage implements StorageProvider {
  readonly name = "S3" as const;
  private clientPromise?: Promise<{ client: import("@aws-sdk/client-s3").S3Client; sdk: typeof import("@aws-sdk/client-s3") }>;

  private async sdk() {
    this.clientPromise ??= import("@aws-sdk/client-s3").then((sdk) => ({
      sdk,
      client: new sdk.S3Client({
        region: env.S3_REGION,
        endpoint: env.S3_ENDPOINT || undefined,
        forcePathStyle: env.S3_FORCE_PATH_STYLE,
        credentials: { accessKeyId: env.S3_ACCESS_KEY_ID!, secretAccessKey: env.S3_SECRET_ACCESS_KEY! },
      }),
    }));
    return this.clientPromise;
  }

  async put(key: string, body: Buffer, contentType: string) {
    assertKey(key);
    const { client, sdk } = await this.sdk();
    await client.send(
      new sdk.PutObjectCommand({ Bucket: env.S3_BUCKET, Key: key, Body: body, ContentType: contentType, CacheControl: "public, max-age=31536000, immutable" }),
    );
  }

  async remove(key: string) {
    assertKey(key);
    const { client, sdk } = await this.sdk();
    await client.send(new sdk.DeleteObjectCommand({ Bucket: env.S3_BUCKET, Key: key }));
  }

  urlFor(key: string) {
    const base = env.S3_PUBLIC_BASE_URL?.replace(/\/$/, "") ?? `${(env.S3_ENDPOINT ?? "").replace(/\/$/, "")}/${env.S3_BUCKET}`;
    return `${base}/${key}`;
  }
}

let instance: StorageProvider | undefined;
export function getStorage(): StorageProvider {
  instance ??= env.MEDIA_STORAGE_PROVIDER === "s3" ? new S3Storage() : new LocalStorage();
  return instance;
}

export function getLocalRoot(): string | null {
  const s = getStorage();
  return s instanceof LocalStorage ? s.root : null;
}

/** Turns a stored `publicUrl` into an absolute URL for API responses. */
export function absoluteMediaUrl(publicUrl: string | null | undefined): string | null {
  if (!publicUrl) return null;
  return publicUrl.startsWith("/") ? `${env.API_PUBLIC_URL.replace(/\/$/, "")}${publicUrl}` : publicUrl;
}
